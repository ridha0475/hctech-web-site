let currentLang = 'fr';
window.__i18nGet = (key) => (STR[currentLang] && STR[currentLang][key]) || STR.fr[key] || key;

function setLang(lang) {
	if (!STR[lang]) lang = 'fr';
	currentLang = lang;
	const dict = STR[lang];
	document.documentElement.lang = lang;
	document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

	document.querySelectorAll('[data-i18n]').forEach((el) => {
		const key = el.getAttribute('data-i18n');
		if (dict[key] != null) el.textContent = dict[key];
	});
	document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
		const value = dict[el.dataset.i18nAlt];
		if (value != null) el.setAttribute('alt', value);
	});
	document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
		const value = dict[el.dataset.i18nAriaLabel];
		if (value != null) el.setAttribute('aria-label', value);
	});

	const page = document.body.dataset.page;
	if (page) {
		document.title = dict[`meta.${page}.title`] || document.title;
		const description = document.querySelector('meta[name="description"]');
		if (description && dict[`meta.${page}.description`]) description.content = dict[`meta.${page}.description`];
	}

	// Rename the four field states (HUD + scene labels read these).
	dict.states.forEach((name, i) => { if (STATES[i]) STATES[i].name = name; });

	document.querySelectorAll('.nav__lang button').forEach((b) => {
		b.classList.toggle('is-active', b.dataset.lang === lang);
	});
	try { localStorage.setItem('hctech-lang', lang); } catch {}
	window.dispatchEvent(new CustomEvent('hctech:lang', { detail: { lang } }));
}

document.querySelectorAll('.nav__lang button').forEach((b) => {
	b.addEventListener('click', () => setLang(b.dataset.lang));
});

const currentPage = location.pathname.split('/').pop() || 'index.html';
document.querySelectorAll('.nav__links a').forEach((link) => {
	if (link.getAttribute('href')?.split('#')[0] === `./${currentPage}`) link.setAttribute('aria-current', 'page');
});

let initial = 'fr';
try { initial = localStorage.getItem('hctech-lang') || 'fr'; } catch {}
setLang(initial);
